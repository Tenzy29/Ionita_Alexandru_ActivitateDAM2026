package com.example.lab4_exercitiu;

public class Autoturism {

    private String denumire;
    private String model;
    private int anFabricate;
    private int capacitateMotor;
    private int nrUsi;

    public String getDenumire() {
        return denumire;
    }

    public void setDenumire(String denumire) {
        this.denumire = denumire;
    }

    public String getModel() {
        return model;
    }

    public void setModel(String model) {
        this.model = model;
    }

    public int getAnFabricate() {
        return anFabricate;
    }

    public void setAnFabricate(int anFabricate) {
        this.anFabricate = anFabricate;
    }

    public int getCapacitateMotor() {
        return capacitateMotor;
    }

    public void setCapacitateMotor(int capacitateMotor) {
        this.capacitateMotor = capacitateMotor;
    }

    public int getNrUsi() {
        return nrUsi;
    }

    public void setNrUsi(int nrUsi) {
        this.nrUsi = nrUsi;
    }
}
